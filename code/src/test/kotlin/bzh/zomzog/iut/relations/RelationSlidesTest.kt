    private inline fun <reified R : Repository<*, *>> Session.repository(): R =
        JpaRepositoryFactory(this).getRepository(R::class.java)

    private fun SessionFactory.phoneNumbers(): List<String> = fromTransaction { session ->
        session.createNativeQuery("select phone_number from phone", String::class.java).list()
    }

    private fun configuration(entities: Array<out KClass<*>>) = Configuration().apply {
        entities.forEach { addAnnotatedClass(it.java) }
        setProperty("hibernate.physical_naming_strategy", "org.hibernate.boot.model.naming.PhysicalNamingStrategySnakeCaseImpl")
        setProperty("hibernate.implicit_naming_strategy", "org.springframework.boot.hibernate.SpringImplicitNamingStrategy")
    }

    private fun sessionFactory(entities: Array<out KClass<*>>): SessionFactory = configuration(entities).apply {
        setProperty("hibernate.connection.url", "jdbc:h2:mem:${randomUUID()};DB_CLOSE_DELAY=-1")
        setProperty("hibernate.hbm2ddl.auto", "create")
    }.buildSessionFactory()

    private fun ddl(entities: Array<out KClass<*>>): List<String> {
        val script = File.createTempFile("ddl", ".sql")
        configuration(entities).apply {
            setProperty("hibernate.dialect", "org.hibernate.dialect.PostgreSQLDialect")
            setProperty("hibernate.boot.allow_jdbc_metadata_access", "false")
            setProperty("jakarta.persistence.schema-generation.scripts.action", "create")
            setProperty("jakarta.persistence.schema-generation.scripts.create-target", script.path)
        }.buildSessionFactory().close()
        return script.readLines()
            .filter { it.isNotBlank() && !it.startsWith("comment on") }
            .map { it.removeSuffix(";") }
            .also { script.delete() }
    }
