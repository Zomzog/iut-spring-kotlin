            "create table phone (id bigint generated by default as identity, email varchar(255) unique, phone_number varchar(255), primary key (id))",
            "create table users (email varchar(255) not null, name varchar(255), phone_email varchar(255) unique, primary key (email))",
            "alter table if exists users add constraint FK1qj2mfat2o9nn5mp097e50otl foreign key (phone_email) references phone (email)",
        )

        sessionFactory(OneToOneUniFkOnUserUniqueColumn.entities).use { factory ->
            val phone = OneToOneUniFkOnUserUniqueColumn.PhoneEntity(null, "a@iut.fr", "0601020304")
            factory.inTransaction { it.persist(OneToOneUniFkOnUserUniqueColumn.UserEntity("a@iut.fr", "Alice", phone)) }

