    @Test
    fun `orphanRemoval deletes the phone removed from the list`() {
        assertThat(ddl(OneToManyOrphanRemoval.entities))
            .containsExactlyInAnyOrder(USERS, PHONE_WITH_USER, PHONE_TO_USERS)

        sessionFactory(OneToManyOrphanRemoval.entities).use { factory ->
            val user = OneToManyOrphanRemoval.UserEntity(null, "Alice")
            val kept = OneToManyOrphanRemoval.PhoneEntity(null, user, "0601020304")
            val removed = OneToManyOrphanRemoval.PhoneEntity(null, user, "0701020304")
            factory.inTransaction { session ->
                session.persist(user)
                session.persist(kept)
                session.persist(removed)
            }

            factory.inTransaction { session ->
                session.find(OneToManyOrphanRemoval.UserEntity::class.java, user.id)
                    .phones.removeIf { it.id == removed.id }
            }

            val numbers = factory.fromTransaction { session ->
                session.createNativeQuery("select phone_number from phone", String::class.java).list()
            }
            assertThat(numbers).containsExactly("0601020304")
        }
    }

